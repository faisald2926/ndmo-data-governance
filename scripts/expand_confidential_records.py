def contains_kw(text: str, level: str) -> bool:
    return any(kw in text for kw in KEYWORDS[level])


def higher_level_leak(text: str, level: str) -> str | None:
    """Return the first keyword from a HIGHER level found in text (None if clean)."""
    for lvl in LEVELS[RANK[level] + 1:]:
        for kw in KEYWORDS[lvl]:
            if kw in text:
                return f"{lvl}:{kw}"
    return None


def rand_date(rng, start=dt.date(2019, 1, 1), end=dt.date(2026, 6, 20)) -> str:
    return (start + dt.timedelta(days=rng.randrange((end - start).days))).isoformat()


def build_rows(families, level, count, rng, seen, ref_prefix, units):
    """Draw `count` records for `level` from its template families.

    Semantic variety comes from (family x title slots). A trailing reference
    line — the way a real register stores provenance — supplies the remaining
    entropy so every free-text blob is unique without cloning 12 strings 500x.
    """
    out = []
    fams = families[level]
    safe_units = neutral(units)
    attempts = 0
    while len(out) < count:
        attempts += 1
        if attempts > count * 500:
            raise RuntimeError(f"cannot reach {count} unique rows for {level}")
        # Date first: templates read the year through YR()/HZ(), so a title that
        # names a year always agrees with the row's own date column.
        date = rand_date(rng)
        _ACTIVE["year"] = int(date[:4])
        unit = S(safe_units, rng)
        idx = rng.randrange(len(fams))
        title_fn, body_fn, impact, rationale, anchor = fams[idx]
        title = title_fn(rng)
        body = (body_fn(rng) + f" المرجع {ref_prefix}-{YR()}-{rng.randrange(1000, 9999)}"
                               f" · الجهة المعنية: {unit}.")
        blob = f"{title} {body}".strip()
        if blob in seen:
            continue
        leak = higher_level_leak(blob, level)
        if leak:
            raise AssertionError(f"[{level}] leaks higher-level keyword {leak}: {blob}")
        if anchor and anchor not in blob:
            raise AssertionError(f"[{level}] lost its anchor '{anchor}': {blob}")
        if not anchor:
            # A hard case must carry NO keyword at all, so the offline baseline
            # falls back to NDMO's safe default (مقيّد) instead of guessing عام.
            hit = [kw for kws in KEYWORDS.values() for kw in kws if kw in blob]
            if hit:
                raise AssertionError(f"[{level}] hard case is not keyword-free {hit}: {blob}")
        seen.add(blob)
        out.append({"title": title, "body": body, "impact": impact, "family": idx,
                    "rationale": rationale, "level": level, "hard": not anchor,
                    "date": date, "unit": unit})
    return out


