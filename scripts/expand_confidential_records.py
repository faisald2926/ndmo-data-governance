def write_csv(path, header, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def append_csv(path, rows):
    with open(path, "a", encoding="utf-8", newline="") as fh:
        csv.writer(fh, lineterminator="\n").writerows(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data"))
    ap.add_argument("--seed", type=int, default=20260816)
    args = ap.parse_args()
    d = args.data_dir
    rng = random.Random(args.seed)

    # guard: keyword table must still match the classifier
    llm_path = os.path.join(os.path.dirname(d), "app", "classification", "llm.py")
    if os.path.exists(llm_path):
        src = open(llm_path, encoding="utf-8").read()
        for lvl, kws in KEYWORDS.items():
            for kw in kws:
                if f'"{kw}"' not in src:
                    sys.exit(f"KEYWORD DRIFT: '{kw}' ({lvl}) no longer in llm.py")

    seen_text, gt_rows, dq_rows = set(), [], []
    # existing free text must not be duplicated either
    with open(os.path.join(d, "05_documents_register.csv"), encoding="utf-8-sig") as fh:
        for row in csv.DictReader(fh):
            seen_text.add(f"{row['title_ar']} {row['snippet_ar']}".strip())

    summary = {}

    for fname, plan in PLAN.items():
        fams = FAMILY_OF[fname]
        pool = []
        for lvl in (TOP_SECRET, SECRET, RESTRICTED, PUBLIC):
            pool += build_rows(fams, lvl, plan[lvl], rng, seen_text,
                               REF_PREFIX[fname], UNIT_POOL[fname])
        rng.shuffle(pool)

        n_missing = round(len(pool) * MISSING_RATE[fname])
        missing_idx = set(rng.sample(range(len(pool)), n_missing))
        req = REQUIRED_COL[fname]
        rows = []

        if fname == "05_documents_register.csv":
            start = 301
            for i, rec in enumerate(pool):
                rid = f"DOC-{start + i:05d}"
                label = "" if i in missing_idx else rec["level"]
                rows.append([rid, rec["title"], rec["body"], rec["unit"],
                             rec["date"], label])
                gt_rows.append([fname, rid, rec["level"], rec["impact"], DETECTION,
                                rec["rationale"]])
                if i in missing_idx:
                    dq_rows.append([fname, rid, req, "Completeness", "missing_value",
                                    "الحقل المطلوب 'current_label' فارغ"])
            append_csv(os.path.join(d, fname), rows)

        elif fname == "08_security_incidents.csv":
            hdr = ["incident_id", "opened_date", "severity", "affected_system_ar",
                   "incident_title_ar", "incident_summary_ar", "responsible_unit", "status"]
            sev_of = {TOP_SECRET: ["حرجة", "عالية"], SECRET: ["عالية", "متوسطة"],
                      RESTRICTED: ["متوسطة", "منخفضة"], PUBLIC: ["منخفضة"]}
            for i, rec in enumerate(pool):
                rid = f"INC-{i + 1:05d}"
                unit = "" if i in missing_idx else rec["unit"]
                # the affected system must be the one the narrative names
                named = [s for s in SYSTEMS if s in rec["title"] or s in rec["body"]]
                system = max(named, key=len) if named else S(SYSTEMS, rng)
                rows.append([rid, rec["date"], S(sev_of[rec["level"]], rng),
                             system, rec["title"], rec["body"], unit,
                             S(INC_STATUS, rng)])
                gt_rows.append([fname, rid, rec["level"], rec["impact"], DETECTION,
                                rec["rationale"]])
                if i in missing_idx:
                    dq_rows.append([fname, rid, req, "Completeness", "missing_value",
                                    "الحقل المطلوب 'responsible_unit' فارغ"])
            write_csv(os.path.join(d, fname), hdr, rows)

        elif fname == "09_internal_investigations.csv":
            hdr = ["case_id", "reported_date", "case_type", "subject_ar",
                   "case_summary_ar", "handling_unit", "case_status"]
            for i, rec in enumerate(pool):
                rid = f"CASE-{i + 1:05d}"
                unit = "" if i in missing_idx else rec["unit"]
                rows.append([rid, rec["date"], S(CASE_TYPES, rng), rec["title"],
                             rec["body"], unit, S(CASE_STATUS, rng)])
                gt_rows.append([fname, rid, rec["level"], rec["impact"], DETECTION,
                                rec["rationale"]])
                if i in missing_idx:
                    dq_rows.append([fname, rid, req, "Completeness", "missing_value",
                                    "الحقل المطلوب 'handling_unit' فارغ"])
