def S(seq, rng):
    return rng.choice(seq)


# The record's own year, set by build_rows before the templates fire, so a title
# that says "2025" can never sit on a row dated 2020.
_ACTIVE = {"year": 2024}


def YR(_r=None):
    return str(_ACTIVE["year"])


def HZ(r):
    y = _ACTIVE["year"]
    return f"{y}-{y + r.choice([2, 3, 4])}"


def sanitize(pool, max_level):
    """Drop vocabulary entries that carry a keyword belonging to a level ABOVE
    max_level. Without this, a عام record built from 'نظام إدارة الهوية المركزي'
    would trip the RESTRICTED keyword 'هوية' and be mislabelled by the baseline."""
    bad = [kw for lvl in LEVELS[RANK[max_level] + 1:] for kw in KEYWORDS[lvl]]
    return [x for x in pool if not any(k in x for k in bad)]


def neutral(pool):
    """Entries carrying NO classification keyword at any level.

    Used for the provenance tail. 'الخدمات المساندة' embeds the PUBLIC keyword
    'خدمات'; letting it into the free text of a سري record makes the baseline
    predict عام — an over-declassification error invented by the generator
    rather than by the data.
    """
    bad = [kw for kws in KEYWORDS.values() for kw in kws]
    return [x for x in pool if not any(k in x for k in bad)]


